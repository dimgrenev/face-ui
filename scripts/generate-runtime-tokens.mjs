import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join, relative } from 'node:path'
import { generateDesignSystem } from './generate-design-system.mjs'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outputPath = join(root, 'assets/styles/tokens.css')
const write = process.argv.includes('--write')
generateDesignSystem(root, write)

const inputs = [
  'design-system/tokens/colors.css',
  'design-system/tokens/typography.css',
  'design-system/tokens/geometry.css',
  'design-system/tokens/motion.css',
  'design-system/tokens/spacing.css',
  'design-system/tokens/shadows.css',
  'design-system/tokens/borders.css',
  'design-system/themes/default.css',
  'assets/styles/component-tokens.css',
]

const banner = `/**
 * Face UI - Runtime Tokens
 *
 * GENERATED FILE. Run \`pnpm tokens:sync\` after changing design-system
 * tokens, themes, or component-tokens.css. Do not edit this file directly.
 */`

const sections = inputs.map((input) => {
  const contents = readFileSync(join(root, input), 'utf8').trim()
  return `/* Source: ${input} */\n${contents}`
})

const expected = `${[banner, ...sections].join('\n\n')}\n`

if (write) {
  writeFileSync(outputPath, expected)
  console.log(`Updated ${relative(process.cwd(), outputPath)}`)
  process.exit(0)
}

const actual = readFileSync(outputPath, 'utf8')
if (actual !== expected) {
  console.error('Runtime tokens are out of date. Run `pnpm tokens:sync`.')
  process.exit(1)
}

console.log('Runtime tokens are up to date.')
